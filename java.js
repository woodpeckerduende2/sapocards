export function javaDeck(now = Date.now()) {
  return {
    deck: {
      id: JAVA_DECK_ID,
      name: "Java: primeiros passos",
      description:
        "Do primeiro println aos objetos: conceitos, leitura de código e exercícios em 12 lições curtas.",
      category: "Programação",
      color: "blue",
      favorite: false,
      created: now,
    },
    cards: JAVA_TOPICS.flatMap((topic) =>
      lessons[topic.key].map((entry, i) => ({
        id: `${JAVA_DECK_ID}-${topic.key}-${i}`,
        deckId: JAVA_DECK_ID,
        difficulty: topic.level,
        topic: topic.key,
        ...structuredClone(entry),
      })),
    ),
  };
}
export function installJavaPack(data) {
  if (data.contentPacks?.includes(PACK)) return false;
  const p = javaDeck();
  if (
    data.decks.some((d) => d.id === p.deck.id) ||
    p.cards.some((c) => data.cards.some((old) => old.id === c.id))
  )
    return false;
  data.decks.push(p.deck);
  data.cards.push(...p.cards);
  data.contentPacks = [...(data.contentPacks || []), PACK];
  return true;
}
